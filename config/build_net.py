"""config/network.json → config/deskbot_net.h（固件用）。

    python3 config/build_net.py

- deskbot_net.h：WiFi 名 / 密码、中枢端口、发现协议常量。进 git。
- deskbot_net_local.h：只有一行 #define DB_HUB_TOKEN "…"，从 hub/.token 来。**不进 git**。
  固件 #include "deskbot_net.h" 就行，它会自动带上本地令牌（有的话）。
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
cfg = json.loads((HERE / "network.json").read_text())
w, h = cfg["wifi"], cfg["hub"]

# 云端中枢（可选）："cloud_host" / "cloud_port"。设置了就只连云端（wss），不再做局域网 UDP 发现
cloud = ""
if h.get("cloud_host"):
    cloud = f'// 云端中枢：只连这里（wss），不做局域网发现\n#define DB_HUB_CLOUD_HOST "{h["cloud_host"]}"\n#define DB_HUB_CLOUD_PORT {h.get("cloud_port", h["ws_port"])}\n\n'

(HERE / "deskbot_net.h").write_text(f'''// generated by config/build_net.py from config/network.json — 不要手改
#pragma once

#define DB_WIFI_SSID "{w["ssid"]}"
#define DB_WIFI_PASS "{w["password"]}"

#define DB_HUB_WS_PORT {h["ws_port"]}
#define DB_HUB_WS_PATH "{h["ws_path"]}"

// 自动发现：开机连上 WiFi 后广播 DB_DISCOVERY_QUERY 到 UDP DB_DISCOVERY_PORT，中枢回复
// {{"t":"hub","ws_port":…,"path":"…","auth":true}}，地址用回复包的源 IP。详见 双板方案.md
{cloud}#define DB_DISCOVERY_PORT {h["discovery_port"]}
#define DB_DISCOVERY_QUERY "{{\\"t\\":\\"deskbot?\\",\\"v\\":1}}"

#if defined(__has_include)
#  if __has_include("deskbot_net_local.h")
#    include "deskbot_net_local.h"   // 定义 DB_HUB_TOKEN，不进 git
#  endif
#endif
#ifndef DB_HUB_TOKEN
#  define DB_HUB_TOKEN ""           // 空令牌：中枢会拒绝非本机连接。先跑 python3 config/build_net.py
#endif
''')

# 备用 WiFi（比如你自己的手机热点）：config/network_local.json = {"fallback": [{"ssid": "...", "password": "..."}]}，不进 git。
# 主 WiFi 扫不到时，板子会改连这里的第一个能扫到的热点。
fallback = ""
local_net = HERE / "network_local.json"
if local_net.exists():
    fb = json.loads(local_net.read_text()).get("fallback", [])
    for i, f in enumerate(fb[:2], 1):
        fallback += f'#define DB_WIFI_FB{i}_SSID "{f["ssid"]}"\n#define DB_WIFI_FB{i}_PASS "{f["password"]}"\n'

token_file = HERE.parent / "hub" / ".token"
if token_file.exists():
    token = token_file.read_text().strip()
    (HERE / "deskbot_net_local.h").write_text(f'// 本地令牌和备用 WiFi，不进 git\n#define DB_HUB_TOKEN "{token}"\n{fallback}')
    print("wrote config/deskbot_net.h and config/deskbot_net_local.h（含令牌）")
else:
    print("wrote config/deskbot_net.h；还没有 hub/.token：先启动一次 hub/mock_hub.py 再运行本脚本，才会生成 deskbot_net_local.h")
